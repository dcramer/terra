/// Below this want a motif's symbol is banned from a pixel.
pub const BANNED_BELOW: f32 = 0.03;

impl Layer {
    pub fn model(&self) -> Model {
        Model::learn(self.examples, self.n, true)
    }

    /// Each of the model's symbols' weights where the wants are these.
    pub fn weights(&self, model: &Model, wants: &Wants) -> [f32; MAX_SYMBOLS] {
        let mut out = [0.0; MAX_SYMBOLS];
        for (i, &c) in model.symbols.iter().enumerate() {
            out[i] = match self.symbols.iter().find(|s| s.0 == c) {
                Some((_, want, strength)) => {
                    let w = want(wants);
                    if w < BANNED_BELOW { 0.0 } else { w * strength }
                }
                None => 1.0,
            };
        }
        out
    }
}
