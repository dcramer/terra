//! The weathering motifs, as example patches the overlapping model learns from, a layer
//! each: what a patch shows is what the solver may make, a crack's pixels joined as a
//! crack's are, moss in patches, streaks a pixel wide and running down.

use crate::masks::Wants;
use crate::wfc::{MAX_SYMBOLS, Model};

/// A symbol, its want and the want's strength.
pub type Symbol = (char, fn(&Wants) -> f32, f32);

/// A motif layer: its examples, how it is learned and how finely it is solved.
pub struct Layer {
    pub examples: &'static [&'static str],
    /// The pattern's side: 3 for lines that must join and branch, 2 for patches.
    pub n: usize,
    /// Pixels a side of a half-metre face.
    pub per_cell: usize,
    /// For each of its symbols other than '.', its want's strength.
    pub symbols: &'static [Symbol],
}

